import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('login, keyboard access, responsive layout and accessibility',async({page})=>{
  await page.setViewportSize({width:1440,height:1100})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'교수자 로그인'})).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link',{name:'본문으로 건너뛰기'})).toBeFocused()
  await page.screenshot({path:'../../artifacts/screenshots/workspace-desktop.png',fullPage:true})
  const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze()
  expect(result.violations).toEqual([])
  for(const width of [360,768]){
    await page.setViewportSize({width,height:950})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
    await page.screenshot({path:`../../artifacts/screenshots/workspace-${width}.png`,fullPage:true})
  }
})

test('real REST transport: upload → draft → revise → approve → download → feedback',async({page})=>{
  await page.goto('/')
  await page.getByLabel('API 주소').fill('http://127.0.0.1:8100')
  await page.getByLabel('교수자 초대 토큰').fill('e2e-alice-token')
  await page.getByRole('button',{name:'로그인'}).click()
  await expect(page.getByText('연결된 API가 demo 모드입니다.',{exact:false})).toBeVisible()
  await page.getByRole('button',{name:'새 강의'}).click()
  await page.getByLabel('강의 이름').fill('E2E '+Date.now())
  await page.getByLabel('강의계획서',{exact:true}).fill('1주차 지도학습')
  await page.getByRole('button',{name:'강의 만들기',exact:true}).click()
  await page.getByRole('button',{name:/강의 자료실/}).click()
  await page.locator('input[type=file]').setInputFiles({name:'source.md',mimeType:'text/markdown',buffer:Buffer.from('# 지도학습\n정답이 있는 데이터로 학습합니다.')})
  await expect(page.getByText('source.md',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'강의 작업실',exact:true}).click()
  await page.getByLabel('이번 주 주제').fill('지도학습의 원리')
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'초안 만들기'}).click()
  await expect(page.getByRole('button',{name:'v1 승인'})).toBeVisible()
  await page.getByLabel('수정 요청',{exact:true}).fill('예시를 추가해 주세요')
  await page.getByRole('button',{name:'수정 요청',exact:true}).click()
  await expect(page.getByRole('button',{name:'v2 승인'})).toBeVisible()
  await page.getByRole('button',{name:'v2 승인'}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'결과 다운로드'}).click()
  expect((await download).suggestedFilename()).toMatch(/lecture-2\.md/)
  await page.getByRole('button',{name:'피드백 보내기'}).click()
  await expect(page.getByText('피드백이 저장됐습니다.')).toBeVisible()
  await page.screenshot({path:'../../artifacts/screenshots/review-complete.png',fullPage:true})
})
